-- ============================================================
-- SECURE FILE SHARING
-- ============================================================

CREATE TABLE public.case_secure_share (
    id BIGSERIAL PRIMARY KEY,
    case_record_id BIGINT NOT NULL,
    recipient_name VARCHAR(255) NOT NULL,
    recipient_email VARCHAR(255) NOT NULL,
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    access_code_hash VARCHAR(255),
    allow_view BOOLEAN NOT NULL DEFAULT TRUE,
    allow_download BOOLEAN NOT NULL DEFAULT TRUE,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITHOUT TIME ZONE,
    max_downloads INTEGER,
    download_count INTEGER NOT NULL DEFAULT 0,
    created_by VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_accessed_at TIMESTAMP WITHOUT TIME ZONE,
    access_code_expires_at TIMESTAMP WITHOUT TIME ZONE,
    access_code_attempts INTEGER NOT NULL DEFAULT 0,
    verified_at TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT fk_secure_share_case
        FOREIGN KEY (case_record_id)
        REFERENCES public.case_record(id)
        ON DELETE CASCADE
);

ALTER TABLE public.case_secure_share OWNER TO bms;
ALTER SEQUENCE public.case_secure_share_id_seq OWNER TO bms;

CREATE TABLE public.case_secure_share_file (
    secure_share_id BIGINT NOT NULL,
    patient_file_id BIGINT NOT NULL,

    CONSTRAINT case_secure_share_file_pkey
        PRIMARY KEY (secure_share_id, patient_file_id),

    CONSTRAINT fk_secure_share_file_share
        FOREIGN KEY (secure_share_id)
        REFERENCES public.case_secure_share(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_secure_share_file_patient_file
        FOREIGN KEY (patient_file_id)
        REFERENCES public.patient_file(id)
        ON DELETE CASCADE
);

ALTER TABLE public.case_secure_share_file OWNER TO bms;

