-- ============================================================
-- CENTRALIZED CASE ISSUES
-- ============================================================

CREATE TABLE public.case_issue (
    id BIGSERIAL PRIMARY KEY,
    case_record_id BIGINT NOT NULL,
    issue_type VARCHAR(100) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    blocking BOOLEAN NOT NULL DEFAULT FALSE,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    created_by VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_by VARCHAR(255),
    resolved_at TIMESTAMP WITHOUT TIME ZONE,
    resolution_note TEXT,

    CONSTRAINT fk_case_issue_case_record
        FOREIGN KEY (case_record_id)
        REFERENCES public.case_record(id)
        ON DELETE CASCADE
);

ALTER TABLE public.case_issue OWNER TO bms;
ALTER SEQUENCE public.case_issue_id_seq OWNER TO bms;

