-- ============================================================
-- CASE RECORD
-- ============================================================

CREATE TABLE public.case_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    completed_date TIMESTAMP(6) WITHOUT TIME ZONE,
    duramap_sent_date DATE,
    duramap_status VARCHAR(255),
    final_outcome VARCHAR(255),
    imeka_sent_date DATE,
    imeka_status VARCHAR(255),
    neuroreader_sent_date DATE,
    neuroreader_status VARCHAR(255),
    notes TEXT,
    patient_id VARCHAR(255),
    patient_last_name VARCHAR(255),
    patient_status VARCHAR(255),
    site_name VARCHAR(255),
    processing_outcome VARCHAR(255),
    duramap_error_note TEXT,
    imeka_error_note TEXT,
    neuroreader_error_note TEXT,
    images_received_date DATE,
    patient_first_name VARCHAR(255),
    date_of_birth DATE,
    date_scanned DATE,
    funder VARCHAR(255),
    intake_sheet_done BOOLEAN,
    intake_sheet_sent BOOLEAN,
    processed_date TIMESTAMP(6) WITHOUT TIME ZONE,
    owner_group VARCHAR(255),
    assigned_to_user VARCHAR(255),
    imeka_uploaded_date TIMESTAMP WITHOUT TIME ZONE,
    sex VARCHAR(255),
    final_workflow_notes TEXT,
    study_instance_uid VARCHAR(255),
    accession_number VARCHAR(255),
    dicom_linked BOOLEAN DEFAULT FALSE,
    invoice_sent_date DATE,

    CONSTRAINT case_record_duramap_status_check CHECK (
        duramap_status IN ('NOT_SENT', 'SENT', 'COMPLETED', 'UPLOADED', 'ERROR')
    ),
    CONSTRAINT case_record_final_outcome_check CHECK (
        final_outcome IN (
            'COMPLETED',
            'COMPLETED_WITH_THIRD_PARTY_ERRORS',
            'COMPLETED_WITH_ERRORS',
            'UNCOMPLETED',
            'RESCAN_NEEDED'
        )
    ),
    CONSTRAINT case_record_imeka_status_check CHECK (
        imeka_status IN ('NOT_SENT', 'SENT', 'COMPLETED', 'UPLOADED', 'ERROR')
    ),
    CONSTRAINT case_record_neuroreader_status_check CHECK (
        neuroreader_status IN ('NOT_SENT', 'SENT', 'COMPLETED', 'UPLOADED', 'ERROR')
    ),
    CONSTRAINT case_record_patient_status_check CHECK (
        patient_status IN (
            'UPCOMING',
            'VERIFYING',
            'ACQUIRED',
            'PROCESSING',
            'PROCESSED',
            'COMPLETED',
            'ON_HOLD',
            'MISSING_DATA',
            'RESCAN_REQUIRED',
            'REPORT_CORRECTION_REQUIRED',
            'CANCELLED'
        )
    ),
    CONSTRAINT case_record_processing_outcome_check CHECK (
        processing_outcome IN ('PENDING', 'UPLOADED', 'DURAMAP_SENT')
    )
);

ALTER TABLE public.case_record OWNER TO bms;

-- ============================================================
-- SITES
-- ============================================================

CREATE TABLE public.site (
    id BIGSERIAL PRIMARY KEY,
    facility_name VARCHAR(255),
    address VARCHAR(255),
    address_line_1 VARCHAR(255),
    address_line_2 VARCHAR(255),
    city VARCHAR(100),
    state VARCHAR(10),
    zip_code VARCHAR(20),
    primary_contact VARCHAR(255),
    transfer_method VARCHAR(255),
    imeka_certified BOOLEAN,
    scanner_brand VARCHAR(255),
    magnet_strength VARCHAR(255),
    active BOOLEAN DEFAULT TRUE,
    notes TEXT
);

ALTER TABLE public.site OWNER TO bms;
ALTER SEQUENCE public.site_id_seq OWNER TO bms;

CREATE TABLE public.site_contact (
    id BIGSERIAL PRIMARY KEY,
    site_id BIGINT NOT NULL,
    contact_name VARCHAR(255),
    title VARCHAR(255),
    email VARCHAR(255),
    phone VARCHAR(50),

    CONSTRAINT fk_site_contact_site
        FOREIGN KEY (site_id)
        REFERENCES public.site(id)
        ON DELETE CASCADE
);

ALTER TABLE public.site_contact OWNER TO bms;
ALTER SEQUENCE public.site_contact_id_seq OWNER TO bms;

